#!/usr/bin/env python3
"""Derive roles/common_calico/templates/calico-policy-only.yml.j2 from upstream.

    scripts/calico-derive-manifest.py v3.33.0            # downloads canal.yaml
    scripts/calico-derive-manifest.py v3.33.0 canal.yaml # or uses a local copy

Calico runs here in "policy-only" mode next to K3s's own Flannel: only Felix
(calico-node) and kube-controllers, no CNI install, no IPAM, no Flannel. The
official Canal manifest (Calico for policy + Flannel for networking) is the
closest upstream starting point; this script applies the same edits to it on
every version, so a Calico upgrade is "run the script, review the diff, test"
instead of hand-editing 13,000 lines:

  1. drop the Flannel and CNI pieces K3s already provides: the canal-config
     ConfigMap, the flannel and calico-cni-plugin RBAC and ServiceAccounts
  2. rename the canal ServiceAccount/DaemonSet/ClusterRoleBinding to
     calico-node. Its ClusterRole also gets what upstream grants the dropped
     calico-cni-plugin account, because our calico-node is that account too:
     serviceaccounts/token for calico-node, ipamhandles get/list/watch/delete
     (without them calico-node stayed at 0/1 Ready, verified live)
  3. DaemonSet: keep only the calico-node container, no init containers
     (cni-plugins/install-cni/ebpf-bootstrap), only the volumes it uses -
     and cni-net-dir as an emptyDir, so Calico never touches K3s's real
     /etc/cni/net.d;
     CLUSTER_TYPE=k8s, NO_DEFAULT_POOLS=true, FELIX_IPTABLESBACKEND=NFT, no
     USE_POD_CIDR, no envFrom,
     a CPU request of 100m instead of 250m
  4. kube-controllers: ENABLED_CONTROLLERS=node (no load balancer controller)
  5. image tags become {{ calico_version }}

RBAC is kept exactly as upstream ships it: calico-node's internal loops need
it even in policy-only mode (trimming it left the pod stuck at 0/1 Ready).
"""
import re
import sys
import urllib.request
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / 'roles/common_calico/templates/calico-policy-only.yml.j2'
DROP = {('ConfigMap', 'canal-config'), ('ClusterRole', 'flannel'), ('ClusterRoleBinding', 'canal-flannel'),
        ('ClusterRole', 'calico-cni-plugin'), ('ClusterRoleBinding', 'calico-cni-plugin'),
        ('ServiceAccount', 'calico-cni-plugin')}
KEEP_VOLUMES = ['cni-net-dir', 'lib-modules', 'xtables-lock', 'var-run-calico', 'var-lib-calico']

HEADER = """# =============================================================================
# Calico "policy-only" mode for K3s (Flannel networking untouched).
#
# GENERATED by scripts/calico-derive-manifest.py from the official Canal
# manifest of Calico {version} - do not edit by hand, change the script and
# re-run it (its docstring lists every edit). Upstream:
# https://raw.githubusercontent.com/projectcalico/calico/{version}/manifests/canal.yaml
#
# K3s's built-in Flannel handles pod IP allocation, routing and the CNI
# plugin (10-flannel.conflist). This manifest adds ONLY Calico's Felix policy
# engine and kube-controllers, reading Pod/Namespace/NetworkPolicy objects
# straight from the Kubernetes API (DATASTORE_TYPE=kubernetes,
# CALICO_NETWORKING_BACKEND=none, no BGP, no IPAM, no CNI install) and
# programming the rules that enforce networking.k8s.io/v1 NetworkPolicies.
# =============================================================================
"""


def env_set(env, name, value=None, drop=False):
    env[:] = [e for e in env if e['name'] != name]
    if not drop:
        env.append({'name': name, 'value': value})


def transform(docs):
    out = []
    for d in docs:
        kind, name = d['kind'], d['metadata']['name']
        if (kind, name) in DROP:
            continue
        if kind == 'ServiceAccount' and name == 'canal':
            d['metadata']['name'] = 'calico-node'
        if kind == 'ClusterRoleBinding' and name == 'canal-calico':
            d['metadata']['name'] = 'calico-node'
            for s in d['subjects']:
                if s.get('name') == 'canal':
                    s['name'] = 'calico-node'
        if kind == 'ClusterRole' and name == 'calico-node':
            for r in d['rules']:
                if 'serviceaccounts/token' in r.get('resources', []) and 'calico-node' not in r.get('resourceNames', []):
                    r['resourceNames'].append('calico-node')
                if 'ipamblocks' in r.get('resources', []) and 'ipamhandles' not in r['resources'] \
                        and set(r['verbs']) == {'get', 'list', 'watch'}:
                    r['resources'].insert(r['resources'].index('ipamblocks') + 1, 'ipamhandles')
            d['rules'].append({'apiGroups': ['projectcalico.org', 'crd.projectcalico.org'],
                               'resources': ['ipamhandles'], 'verbs': ['delete']})
        if kind == 'DaemonSet' and name == 'canal':
            d['metadata']['name'] = 'calico-node'
            for labels in (d['metadata'].setdefault('labels', {}), d['spec']['selector']['matchLabels'],
                           d['spec']['template']['metadata']['labels']):
                labels['k8s-app'] = 'calico-node'
            spec = d['spec']['template']['spec']
            spec['serviceAccountName'] = 'calico-node'
            spec.pop('initContainers', None)
            spec['containers'] = [c for c in spec['containers'] if c['name'] == 'calico-node']
            c = spec['containers'][0]
            c.pop('envFrom', None)
            env_set(c['env'], 'USE_POD_CIDR', drop=True)
            env_set(c['env'], 'CLUSTER_TYPE', 'k8s')
            env_set(c['env'], 'NO_DEFAULT_POOLS', 'true')
            # nftables only: never fall back to iptables-legacy, even if a
            # host still has legacy rules (the auto-detection followed them)
            env_set(c['env'], 'FELIX_IPTABLESBACKEND', 'NFT')
            c['resources'] = {'requests': {'cpu': '100m'}}
            c['volumeMounts'] = [m for m in c['volumeMounts'] if m['name'] in KEEP_VOLUMES]
            spec['volumes'] = [{'name': 'cni-net-dir', 'emptyDir': {}} if v['name'] == 'cni-net-dir' else v
                               for v in spec['volumes'] if v['name'] in KEEP_VOLUMES]
        if kind == 'Deployment' and name == 'calico-kube-controllers':
            for c in d['spec']['template']['spec']['containers']:
                for e in c.get('env', []):
                    if e['name'] == 'ENABLED_CONTROLLERS':
                        e['value'] = 'node'
        out.append(d)
    return out


def main():
    version = sys.argv[1]
    src = Path(sys.argv[2]).read_text() if len(sys.argv) > 2 else urllib.request.urlopen(
        f'https://raw.githubusercontent.com/projectcalico/calico/{version}/manifests/canal.yaml').read().decode()
    docs = transform([d for d in yaml.safe_load_all(src) if d])
    body = '\n'.join('---\n' + yaml.safe_dump(d, sort_keys=False, width=120) for d in docs)
    body = re.sub(r'(image: \S+):' + re.escape(version) + r'\b', r'\1:{{ calico_version }}', body)
    assert version not in body, 'an image tag was not templated'
    OUT.write_text(HEADER.format(version='{{ calico_version }}') + '\n' + body)
    kinds = {}
    for d in docs:
        kinds[d['kind']] = kinds.get(d['kind'], 0) + 1
    print(f'{OUT.relative_to(REPO)}: {len(docs)} objects', kinds)


if __name__ == '__main__':
    main()
